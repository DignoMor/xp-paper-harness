import { afterEach, beforeEach, expect, it } from 'vitest';
import { createTestHarness, type TestHarness } from './helpers/harness.js';
import { PaperAgent, type AgentEvent } from '../src/agent/paper-agent.js';
import { OpenCodeGoProvider } from '../src/llm/opencode-go-provider.js';
import { PdfjsReader } from '../src/infrastructure/pdf/pdfjs-reader.js';
import { buildTextPdf } from './fixtures/pdf.js';
import { reply } from '../scripts/acceptance-provider.mjs';
import { APPROVED_TOOL_NAMES } from '../src/agent/system-prompt.js';
import { LibraryService } from '../src/application/library-service.js';
import { ReadingService } from '../src/application/reading-service.js';
import { systemClock } from '../src/application/ports.js';
let h: TestHarness;
beforeEach(async () => { h = await createTestHarness(); });
afterEach(async () => { await h.cleanup(); });
it('runs the container provider fixture through real metadata, import/read/note tools, and stable provider headers', async () => {
  const captured: Array<{ session: string; body: any }> = [];
  const provider = new OpenCodeGoProvider({ apiKey: 'offline-fixture', fetchImpl: async (_input, init) => {
    const body = JSON.parse(String(init!.body));
    const session = new Headers(init!.headers).get('x-session-id')!;
    captured.push({ session, body });
    return new Response(`data: ${JSON.stringify(reply(body))}\n\ndata: [DONE]\n\n`, { headers: { 'content-type': 'text/event-stream' } });
  } });
  const pdf = new PdfjsReader();
  const library = new LibraryService({ catalog: h.catalog, notes: h.noteStore, uploads: h.uploads, paths: h.paths, pdf, clock: systemClock });
  const reading = new ReadingService({ catalog: h.catalog, pdf, library, limits: h.config.pdf });
  const agent = new PaperAgent({ provider, conversations: h.conversations, services: { library, notes: h.noteService, reading, reconciliation: h.reconciliation } });
  const run = async (prompt: string, conversation_id?: string) => {
    const events: AgentEvent[] = [];
    for await (const event of agent.run({ prompt, conversation_id })) events.push(event);
    expect(events.at(-1)?.type).toBe('done');
    expect(events.some(e => e.type === 'error' || e.type === 'tool_result' && !e.ok)).toBe(false);
    return events;
  };
  const upload = await h.stage(buildTextPdf());
  const imported = await run(`import fixture\n\n[staged upload] upload_id=${upload}`);
  const first = imported[0] as Extract<AgentEvent, { type: 'conversation' }>;
  const id = first.conversation.conversation_id;
  const paper = (await library.listPapers())[0]!;
  const detail = await library.getPaper(paper.paper_id);
  expect(detail.metadata).toMatchObject({ title: 'Fixture Title', creators: [{ name: 'Paper Harness Fixture' }] });
  expect(detail.attachments[0]).toMatchObject({ page_count: 3, extraction_status: 'ok' });
  const read = await run(`read ${paper.paper_id}`, id);
  expect(JSON.stringify(read)).toContain("Page One Alpha");
  await run(`note ${paper.paper_id}`, id);
  expect((await h.noteService.readNote(paper.paper_id)).body).toContain('Container acceptance note.');
  expect(captured.every(r => r.session === id)).toBe(true);
  const other = await run('ping');
  const secondId = (other[0] as Extract<AgentEvent, { type: 'conversation' }>).conversation.conversation_id;
  expect(secondId).not.toBe(id);
  expect(captured.at(-1)!.session).toBe(secondId);
  for (const request of captured) expect(request.body.tools.map((tool: any) => tool.function.name).sort()).toEqual([...APPROVED_TOOL_NAMES].sort());
  expect(captured.some(r => r.body.messages.some((m: any) => m.role === 'tool' && m.name === 'import_paper'))).toBe(true);
});
